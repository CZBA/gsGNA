read_grn <- function(file, stress) {
  d <- fread(file, showProgress = FALSE)
  required_columns <- c("TF", "Target", "EdgeWeight")
  if (!all(required_columns %in% names(d))) {
    stop(
      "Top 10% GRN must contain TF, Target and EdgeWeight columns: ", file,
      "\nFound: ", paste(names(d), collapse = ", ")
    )
  }

  d <- d[, .(
    TF = norm_gid(TF),
    Target = norm_gid(Target),
    Weight = suppressWarnings(as.numeric(EdgeWeight))
  )]
  d <- d[
    !is.na(TF) & !is.na(Target) & is.finite(Weight) & TF != Target
  ]
  setorder(d, TF, Target, -Weight)
  d <- unique(d, by = c("TF", "Target"))
  d[, Stress := stress]
  d
}
