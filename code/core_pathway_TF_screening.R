              Abiotic_Stress_Evidence = "Not_reviewed", PMID_DOI = "",
              Evidence_Note = "")]
if (file.exists(biomart_file) && nrow(review)) {
  bio <- fread(biomart_file, sep = "\t", header = TRUE, showProgress = FALSE)
  if (ncol(bio) >= 3L) {
    bm <- unique(data.table(RAP = norm_rap(bio[[1]]),
                            Annotation = trimws(as.character(bio[[3]]))))
    bm <- bm[!is.na(RAP) & !is.na(Annotation) & nzchar(Annotation)]
    if (nrow(bm)) {
      tf_rap <- suppressMessages(AnnotationDbi::select(
        org.Osativa.eg.db::org.Osativa.eg.db,
        keys = sort(unique(review$TF)), keytype = "GID", columns = "RAP"
      ))
      tf_rap <- unique(as.data.table(tf_rap)[, .(TF = norm_gid(GID), RAP = norm_rap(RAP))])
      anno <- merge(tf_rap, bm, by = "RAP", all = FALSE)
      anno <- anno[!is.na(TF), .(
        TF_Annotation = paste(sort(unique(Annotation)), collapse = " | ")
      ), by = TF]
      review[anno, TF_Annotation := i.TF_Annotation, on = "TF"]
    }
  }
}
