screen_one <- function(edges, sc) {
  a_only <- setdiff(sc$A, sc$B)
  b_only <- setdiff(sc$B, sc$A)
  if (!length(a_only) || !length(b_only)) return(NULL)
  e <- edges[Target %chin% union(sc$A, sc$B)]
  if (!nrow(e)) return(NULL)
  e[, `:=`(A_Only = Target %chin% a_only,
           B_Only = Target %chin% b_only,
           A_Any = Target %chin% sc$A,
           B_Any = Target %chin% sc$B)]
  z <- e[, .(
    N_Matched_Targets = uniqueN(Target),
    A_Exclusive_n = uniqueN(Target[A_Only]),
    B_Exclusive_n = uniqueN(Target[B_Only]),
    A_Any_n = uniqueN(Target[A_Any]),
    B_Any_n = uniqueN(Target[B_Any]),
    Matched_Targets = paste(sort(unique(Target)), collapse = "|"),
    A_Exclusive_Targets = paste(sort(unique(Target[A_Only])), collapse = "|"),
    B_Exclusive_Targets = paste(sort(unique(Target[B_Only])), collapse = "|"),
    Mean_Weight = mean(Weight),
    Max_Weight = max(Weight)
  ), by = .(Stress, TF)]
  if (strict_exclusive) {
    z <- z[A_Exclusive_n > 0L & B_Exclusive_n > 0L]
  } else {
    z <- z[A_Any_n > 0L & B_Any_n > 0L & N_Matched_Targets >= 2L]
  }
  if (!nrow(z)) return(NULL)
  z[, `:=`(Scenario = sc$id, Is_Hub = TF %chin% hubs[[unique(Stress)]])]
  z[, Hub_Status := fifelse(Is_Hub, "Hub TF", "Non-hub TF")]
  setcolorder(z, c("Scenario", "Stress", "TF", "Hub_Status", "Is_Hub",
                   setdiff(names(z), c("Scenario", "Stress", "TF", "Hub_Status", "Is_Hub"))))
  z
}
