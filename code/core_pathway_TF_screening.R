check_exists <- function(paths, label) {
  missing <- paths[!file.exists(paths)]
  if (length(missing)) {
    stop(label, " missing file(s):\n", paste(missing, collapse = "\n"))
  }
}

norm_gid <- function(x) {
  x <- toupper(trimws(as.character(x)))
  x <- sub("\\.[0-9]+$", "", x)
  x <- sub("^LOC_OS([0-9]{2})G([0-9]{5})$", "LOC_Os\\1g\\2", x, perl = TRUE)
  x[!grepl("^LOC_Os[0-9]{2}g[0-9]{5}$", x) | is.na(x)] <- NA_character_
  x
}
norm_rap <- function(x) {
  x <- toupper(trimws(as.character(x)))
  x <- sub("^OS([0-9]{2})T([0-9]{7})(-[0-9]+)?$", "Os\\1g\\2", x, perl = TRUE)
  x <- sub("^OS([0-9]{2})G([0-9]{7})$", "Os\\1g\\2", x, perl = TRUE)
  x[!grepl("^Os[0-9]{2}g[0-9]{7}$", x) | is.na(x)] <- NA_character_
  x
}
read_hubs <- function(path) {
  x <- readLines(path, warn = FALSE, encoding = "UTF-8")
  x <- trimws(sub("[,\\t].*$", "", x))
  x <- x[nzchar(x) & !toupper(x) %in% c("TF", "TF_ID", "SOURCE", "GENE_ID", "GID")]
  unique(na.omit(norm_gid(x)))
}
extract_rap <- function(url) {
  m <- regmatches(url, gregexpr("Os[0-9]{2}t[0-9]{7}-[0-9]+", url, perl = TRUE))[[1]]
  unique(na.omit(norm_rap(m)))
}
read_kobas <- function(path) {
  check_exists(path, "KOBAS")
  raw <- readLines(path, warn = FALSE, encoding = "UTF-8")
  h <- grep("^#Term\\t", raw, value = TRUE)
  if (!length(h)) stop("KEGG 文件缺少 #Term 制表符表头")
  rows <- raw[grepl("\\t", raw, fixed = FALSE) & !grepl("^#", raw)]
  if (!length(rows)) stop("KOBAS 文件没有有效数据行")
  d <- fread(text = paste(c(substring(h[1], 2), rows), collapse = "\n"),
             sep = "\t", header = TRUE, quote = "", check.names = FALSE)
  required <- c("Term", "ID", "Input number", "Corrected P-Value", "Input", "Hyperlink")
  if (!all(required %in% names(d))) stop("KOBAS 缺少列: ", paste(setdiff(required, names(d)), collapse = ", "))
  setnames(d, required, c("Pathway", "Pathway_ID", "Input_N", "FDR", "Input_Symbols", "Hyperlink"))
  d[, `:=`(Input_N = as.integer(Input_N), FDR = as.numeric(FDR))]
  unique(d[grepl("^dosa[0-9]+$", Pathway_ID)], by = "Pathway_ID")
}
make_scenario <- function(id, A, B, kind, label, removed = "") {
